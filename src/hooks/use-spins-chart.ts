const parseDateParam = (value: string | null): Date | undefined => {
  if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return undefined;

  const [year, month, day] = value.split("-").map(Number);
  const date = new Date(year, month - 1, day);

  if (
    date.getFullYear() !== year ||
    date.getMonth() !== month - 1 ||
    date.getDate() !== day
  ) {
    return undefined;
  }

  return date;
};

const formatDateForAPI = (date: Date): string => {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
};

const formatDateRange = (range?: DateRange): string => {
  if (!range?.from || !range.to) return "Select date range";

  const fmt = (d: Date): string =>
    d.toLocaleDateString("en-US", {
      month: "short",
      day: "numeric",
      year: "numeric",
    });

  return `${fmt(range.from)} - ${fmt(range.to)}`;
};

const mapApiDataToChartData = (apiData: any[]): ChartData[] => {
  return apiData.map((item, index) => {
    // Titles can arrive as "Song by Artist".
    const titleParts = item.title.split(" by ");
    const song = titleParts[0] || item.title;
    const artist = titleParts[1] || item.artist || "";
    const position = item.position || index + 1;
    const lastWeek = item.lw || null;

    return {
      position,
      song: song.trim(),
      artist: artist.trim(),
      songUrl: item.spotify_id
        ? `https://open.spotify.com/track/${item.spotify_id}`
        : "",
      spins: item.spin_count || 0,
      lastWeek,
      peak: 0,
      weeks: item.woc || 0,
      movement: lastWeek ? lastWeek - position : null,
      status: item.status || "",
      genre: item.genre || "",
      location: item.top_locations?.[0]?.location || "",
      dj: item.top_djs?.[0]?.dj_name || "",
    };
  });
};

const toExportRow = (row: ChartData) => [
  row.position,
  row.song,
  row.artist,
  row.spins,
  row.lastWeek || "—",
  row.peak || "—",
  row.weeks || "—",
  row.genre,
];

export function useSpinsChart() {
  const [dateRange, setDateRange] = useState<DateRange>();
  const [datesReady, setDatesReady] = useState(false);
  const [calendarOpen, setCalendarOpen] = useState(false);
  const [sortConfig, setSortConfig] = useState<SortConfig>({
    column: null,
    direction: "asc",
  });
  const [tableData, setTableData] = useState<ChartData[]>(initialData);

  useEffect(() => {
    const params = new URLSearchParams(window.location.search);
    const startFromUrl = parseDateParam(params.get("start_date"));
    const endFromUrl = parseDateParam(params.get("end_date"));

    if (startFromUrl && endFromUrl && startFromUrl <= endFromUrl) {
      setDateRange({ from: startFromUrl, to: endFromUrl });
    } else {
      const end = new Date();
      const start = new Date();
      start.setDate(start.getDate() - 7);
      setDateRange({ from: start, to: end });
    }

    setDatesReady(true);
  }, []);

  const startDate = dateRange?.from;
  const endDate = dateRange?.to;
  const formattedDateRange = formatDateRange(dateRange);

  useEffect(() => {
    if (!datesReady || !startDate || !endDate) return;

    getSpinsAnalytics(formatDateForAPI(startDate), formatDateForAPI(endDate))
      .then((fetchedContent: any) => {
        if (
          fetchedContent?.audio_spins &&
          Array.isArray(fetchedContent.audio_spins)
        ) {
          setTableData(mapApiDataToChartData(fetchedContent.audio_spins));
        }
      })
      .catch((err) => {
        console.error("Error fetching analytics data:", err);
      });
  }, [datesReady, startDate, endDate]);

  const handleDateRangeSelect = (range: DateRange | undefined) => {
    setDateRange(range);

    if (!range?.from || !range.to) return;

    const params = new URLSearchParams(window.location.search);
    params.set("start_date", formatDateForAPI(range.from));
    params.set("end_date", formatDateForAPI(range.to));

    const query = params.toString();
    window.history.replaceState(
      null,
      "",
      `${window.location.pathname}${query ? `?${query}` : ""}${window.location.hash}`,
    );
    setCalendarOpen(false);
  };

  const handleSort = (column: SortColumn): void => {
    let direction: "asc" | "desc" = "asc";
    if (sortConfig.column === column && sortConfig.direction === "asc") {
      direction = "desc";
    }

    const sorted = [...tableData].sort((a, b) => {
      const aVal = a[column];
      const bVal = b[column];

      if (typeof aVal === "string" || typeof bVal === "string") {
        return direction === "asc"
          ? String(aVal).localeCompare(String(bVal))
          : String(bVal).localeCompare(String(aVal));
      }

      // New entries (null movement / last week) sort below everything else.
      const aNum = aVal ?? -Infinity;
      const bNum = bVal ?? -Infinity;
      return direction === "asc" ? aNum - bNum : bNum - aNum;
    });

    setTableData(sorted);
    setSortConfig({ column, direction });
  };

  const exportToCSV = (): void => {
    const toCsvCell = (cell: string | number) =>
      `"${String(cell).replace(/"/g, '""')}"`;

    const csvContent = [
      [formattedDateRange],
      EXPORT_HEADERS,
      ...tableData.map(toExportRow),
      ["", FOOTER_TEXT],
    ]
      .map((row) => row.map(toCsvCell).join(","))
      .join("\n");

    const url = URL.createObjectURL(
      new Blob([csvContent], { type: "text/csv;charset=utf-8;" }),
    );
    const link = document.createElement("a");
    link.href = url;
    link.download = "ae-spins.csv";
    link.click();
    URL.revokeObjectURL(url);
  };

  const exportToPDF = (): void => {
    const doc = new jsPDF();

    doc.setFontSize(11);
    doc.setTextColor(40);
    doc.text(formattedDateRange, 14, 16);

    autoTable(doc, {
      head: [EXPORT_HEADERS],
      body: [...tableData.map(toExportRow), ["", FOOTER_TEXT]],
      startY: 24,
      styles: { fontSize: 10, cellPadding: 3 },
      headStyles: { fillColor: [9, 172, 229] },
      columnStyles: { 1: { cellWidth: "auto" } },
    });

    doc.save("ae-spins.pdf");
  };

  const maxSpins = Math.max(...tableData.map((row) => row.spins), 1);
  const spinsIntensity = (spins: number) => Math.max(0.08, spins / maxSpins);

  return {
    tableData,
    sortConfig,
    handleSort,
    dateRange,
    formattedDateRange,
    calendarOpen,
    setCalendarOpen,
    handleDateRangeSelect,
    exportToCSV,
    exportToPDF,
    spinsIntensity,
  };
}
