export type SpinStatus = "NEW" | "HOT" | "BREAKING" | "";

export interface ChartData {
  position: number;
  song: string;
  artist: string;
  songUrl: string;
  spins: number;
  lastWeek: number | null;
  peak: number;
  weeks: number;
  /** Positions gained since last week; null when the song is a new entry. */
  movement: number | null;
  status: SpinStatus;
  genre: string;
  location: string;
  dj: string;
}

export type SortColumn = keyof Omit<ChartData, "songUrl" | "artist">;

interface SortConfig {
  column: SortColumn | null;
  direction: "asc" | "desc";
}

