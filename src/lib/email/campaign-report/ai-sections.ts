import type { CampaignAiInsights, UnknownRecord } from "./types";
import {
  asRecord,
  asString,
  escapeHtml,
  firstPopulatedArray,
  infoNote,
  listItemStyle,
  sectionHeading,
} from "./utils";

const numericClaimPattern =
  /\d|\b(?:zero|one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve|thirteen|fourteen|fifteen|sixteen|seventeen|eighteen|nineteen|twenty|thirty|forty|fifty|sixty|seventy|eighty|ninety|hundred|thousand|million|billion|trillion|percent)\b/i;

export const hasNumericClaim = (value: string) =>
  numericClaimPattern.test(value);

export const getAiSummary = (
  project: UnknownRecord,
  generated?: CampaignAiInsights,
) => {
  if (generated?.summary && !hasNumericClaim(generated.summary)) {
    return generated.summary;
  }

  const aiInsights = asRecord(project.ai_insights);
  const storedSummary = asString(
    project.ai_summary || aiInsights.summary,
  ).trim();
  return hasNumericClaim(storedSummary) ? "" : storedSummary;
};

export const renderAiRecommendations = (
  project: UnknownRecord,
  projectLink: string,
  generated?: CampaignAiInsights,
) => {
  const aiInsights = asRecord(project.ai_insights);
  const recommendations = (
    generated?.recommendations.length
      ? generated.recommendations
      : firstPopulatedArray(
          project.ai_recommendations,
          aiInsights.recommendations,
        )
  )
    .map((value) => {
      if (typeof value === "string") {
        return { title: "Recommendation", body: value.trim() };
      }

      const recommendation = asRecord(value);
      return {
        title: asString(
          recommendation.title || recommendation.heading || "Recommendation",
        ).trim(),
        body: asString(
          recommendation.body ||
            recommendation.description ||
            recommendation.content ||
            recommendation.recommendation,
        ).trim(),
      };
    })
    .filter(({ body }) => body);
  if (recommendations.length === 0) return "";

  const rows = recommendations
    .map(
      ({ title, body }, index) =>
        `<div style="${listItemStyle(index === recommendations.length - 1)}"><table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;"><tr><td valign="top" style="padding:0;"><a href="${projectLink}" target="_blank" style="display:block;text-decoration:none;color:#000;"><div style="font-size:16px;font-weight:bold;color:#000;">${escapeHtml(title)}</div><p style="font-size:13px;color:#666;margin:10px 0 0;line-height:1.5;">${escapeHtml(body)}</p></a><a href="${projectLink}" style="font-size:14px;color:#ff7400;text-decoration:none;font-weight:500;display:inline-block;margin-top:8px;">View Insights</a></td><td valign="top" width="24" style="width:24px;text-align:right;padding-left:8px;color:#999;font-size:24px;font-weight:normal;line-height:1;"><a href="${projectLink}" target="_blank" style="display:block;color:#999;text-decoration:none;font-size:24px;line-height:1;">&rsaquo;</a></td></tr></table></div>`,
    )
    .join("");

  return `<div style="margin-top:24px;">${sectionHeading("https://res.cloudinary.com/dyueswnzk/image/upload/v1759780230/id_xmybbv_syv929.png", "Recommendations", 30)}<div style="margin-top:14px;background-color:#fffaf5;padding:16px;border-radius:10px;border:1px solid #f0e2d5;border-left:3px solid #ff7400;">${rows}</div>${infoNote("Recommendations are generated by AI based on aggregated campaign data and highlight potential actions to help improve campaign performance.", "10px 0 0")}</div>`;
};
